def _extract_sql(text: str) -> str:
    match = re.search(r"```sql\s*(.*?)```", text, re.DOTALL | re.IGNORECASE)
    if match:
        return match.group(1).strip()
    match = re.search(r"(SELECT\s+.+?;)", text, re.DOTALL | re.IGNORECASE)
    return match.group(1).strip() if match else ""


def _section_span(text: str, label: str):
    pattern = rf"(?:^|\n)\s*[#*]*\s*{label}\s*[:*]*\s*(?:\n|$)"
    match = re.search(pattern, text, re.IGNORECASE)
    return match.end() if match else None


def _extract_narrative(text: str) -> str:
    start = _section_span(text, "NARRATIVE")
    if start is None:
        stripped = re.sub(r"```.*?```", "", text, flags=re.DOTALL)
        return stripped.strip()
    next_header = re.search(
        r"(?:^|\n)\s*[#*]*\s*(?:SQL|CHARTS)\s*[:*]*\s*(?:\n|$)",
        text[start:], re.IGNORECASE,
    )
    end = start + next_header.start() if next_header else len(text)
    return text[start:end].strip()


def _extract_json_block(text: str) -> list:
    match = re.search(
        r"(?:^|\n)\s*[#*]*\s*CHARTS\s*[:*]*\s*(?:\n|.)*?```json\s*(.*?)```",
        text, re.DOTALL | re.IGNORECASE,
    )
    candidate = match.group(1) if match else None
    if candidate is None:
        for m in re.finditer(r"```(?:json)?\s*(\[.*?\])\s*```", text, re.DOTALL | re.IGNORECASE):
            candidate = m.group(1)
            break
    if candidate is None:
        m = re.search(r"(\[\s*\{.*?\}\s*\])", text, re.DOTALL)
        if m:
            candidate = m.group(1)
    if candidate is None:
        return []
    try:
        data = json.loads(candidate)
        return [
            spec for spec in data
            if isinstance(spec, dict) and all(k in spec for k in ("type", "x", "y", "title"))
        ]
    except Exception:
        return []


def _resolve_column(name: str, columns) -> str | None:
    if name in columns:
        return name
    lowered = {c.lower().strip(): c for c in columns}
    return lowered.get(str(name).lower().strip())


def _fallback_chart(result_df):
    import pandas as pd
    numeric_cols = [c for c in result_df.columns if pd.api.types.is_numeric_dtype(result_df[c])]
    non_numeric_cols = [c for c in result_df.columns if c not in numeric_cols]
    if not numeric_cols or not non_numeric_cols:
        return None
    x, y = non_numeric_cols[0], numeric_cols[0]
    try:
        x_vals = result_df[x].astype(str).tolist()
        y_vals = [float(v) for v in result_df[y]]
        fig = go.Figure(data=[go.Bar(x=x_vals, y=y_vals)])
        fig.update_layout(title=f"{y} by {x}", template="plotly_white",
                          font=dict(family="Arial", size=13),
                          margin=dict(t=50, b=40, l=40, r=40))
        fig.update_xaxes(title_text=x)
        fig.update_yaxes(title_text=y)
        return fig.to_html(full_html=False, include_plotlyjs=False)
    except Exception:
        return None


def generate_report(gold_paths: list[str], business_intent: str, run_id: str) -> str:
    audit = AuditLogger(run_id)
    try:
        con = duckdb.connect()
        table_names = []
        for path in gold_paths:
            table_name = Path(path).stem
            con.execute(f"CREATE VIEW {table_name} AS SELECT * FROM read_parquet('{path}')")
            table_names.append(table_name)
        first_gold_table = table_names[0]

        schema_blocks = []
        for table_name in table_names:
            columns_df = con.execute(f"DESCRIBE {table_name}").df()
            preview_df = con.execute(f"SELECT * FROM {table_name} LIMIT 5").df()
            schema_blocks.append(
                f"Table: {table_name}\nColumns: {columns_df['column_name'].tolist()}\n"
                f"Preview:\n{preview_df.to_string(index=False)}"
            )

        prompt = (
            f"Business intent: {business_intent}\n\n"
            + "\n\n".join(schema_blocks)
            + "\n\nOutput exactly three labeled sections in this order:\n"
            "SQL: (a single DuckDB-compatible SELECT statement, wrapped in a ```sql fence)\n"
            "NARRATIVE: (2-3 paragraph executive summary in plain English)\n"
            "CHARTS: (a JSON array of chart specs, each with keys: type, x, y, title, "
            "wrapped in a ```json fence)\n"
            "Column names must exactly match those shown in the preview."
        )

        llm_text = call_llm(prompt, max_tokens=3000)
        sql = _extract_sql(llm_text)
        narrative = _extract_narrative(llm_text)
        chart_specs = _extract_json_block(llm_text)

        try:
            if sql:
                result_df = con.execute(sql).df()
            else:
                raise ValueError("no SQL extracted")
        except Exception:
            result_df = con.execute(f"SELECT * FROM {first_gold_table} LIMIT 20").df()

        chart_htmls = []
        for spec in chart_specs:
            try:
                x_col = _resolve_column(spec["x"], result_df.columns)
                y_col = _resolve_column(spec["y"], result_df.columns)
                if x_col is None or y_col is None:
                    continue
                x_vals = result_df[x_col].astype(str).tolist()
                y_vals = [float(v) for v in result_df[y_col]]
                if spec["type"] == "bar":
                    fig = go.Figure(data=[go.Bar(x=x_vals, y=y_vals)])
                elif spec["type"] == "pie":
                    fig = go.Figure(data=[go.Pie(labels=x_vals, values=y_vals)])
                elif spec["type"] == "line":
                    fig = go.Figure(data=[go.Scatter(x=x_vals, y=y_vals, mode="lines+markers")])
                else:
                    continue
                fig.update_layout(title=spec["title"], template="plotly_white",
                                  font=dict(family="Arial", size=13),
                                  margin=dict(t=50, b=40, l=40, r=40))
                if spec["type"] != "pie":
                    fig.update_xaxes(title_text=x_col)
                    fig.update_yaxes(title_text=y_col)
                chart_htmls.append(fig.to_html(full_html=False, include_plotlyjs=False))
            except Exception:
                continue

        if not chart_htmls:
            fallback = _fallback_chart(result_df)
            if fallback:
                chart_htmls.append(fallback)

        table_html = result_df.to_html(index=False, classes="data-table", border=0, na_rep="---")
        chart_divs = "\n".join(f'<div class="chart-box">{c}</div>' for c in chart_htmls)

        html = HTML_TEMPLATE.format(
            run_id=run_id, business_intent=business_intent,
            narrative=narrative or "No narrative generated.",
            table_html=table_html,
            chart_divs=chart_divs or "<p>No charts generated.</p>",
        )

        out_path = REPORTS_DIR / f"report_{run_id[:8]}.html"
        out_path.write_text(html, encoding="utf-8")
        audit.log("reporter", "report_generated", output_path=str(out_path))
        return str(out_path)

    except Exception as e:
        audit.log("reporter", "report_generation_failed", error=str(e))
        out_path = REPORTS_DIR / f"report_{run_id[:8]}.html"
        out_path.write_text(
            f"<html><body><h1>Report Generation Error</h1><p>{e}</p></body></html>",
            encoding="utf-8",
        )
        return str(out_path)